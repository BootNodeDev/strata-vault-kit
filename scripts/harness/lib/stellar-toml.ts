import { Networks } from "@stellar/stellar-sdk"

export const OPEN_FIELDS = [
	"ORG_NAME",
	"ORG_URL",
	"ORG_LOGO",
	"ORG_DESCRIPTION",
	"ORG_OFFICIAL_EMAIL",
	"ORG_SUPPORT_EMAIL",
	"desc",
	"image",
	"anchor_asset_type",
	"anchor_asset",
	"redemption_instructions",
] as const

export const OPERATOR_FIELDS = [
	...OPEN_FIELDS,
	"code",
	"name",
	"status",
] as const

export type OpenField = (typeof OPEN_FIELDS)[number]
export type OperatorField = (typeof OPERATOR_FIELDS)[number]
export type OperatorValues = Partial<Record<OperatorField, string>>

const ANCHOR_ASSET_TYPES = [
	"fiat",
	"crypto",
	"nft",
	"stock",
	"bond",
	"commodity",
	"realestate",
	"other",
] as const

const STATUSES = ["live", "dead", "test", "private"] as const

export interface Sep1Inputs {
	networkPassphrase?: string
	shareToken?: {
		contract: string
		code: string
		name: string
		decimals: number
	}
	report?: {
		proofUri: string
		proofHash: string
		acceptedAt: bigint
		expiresAt: bigint
	}
	feed?: string
}

export interface MissingField {
	field: string
	reason: string
}

const VERSION = "2.7.0"
const CODE_LIMIT = 12
const NAME_LIMIT = 20
const DISPLAY_DECIMALS_LIMIT = 7

const DOCUMENTATION_FIELDS: OpenField[] = [
	"ORG_NAME",
	"ORG_URL",
	"ORG_LOGO",
	"ORG_DESCRIPTION",
	"ORG_OFFICIAL_EMAIL",
	"ORG_SUPPORT_EMAIL",
]

// Kept for the committed template, which is the renderer's output with no
// inputs at all; a real deployment always has a share token, so this never
// shows up in a file an operator generates and publishes.
const TEMPLATE_HEADER = [
	"# SEP-1 asset metadata (stellar.toml) for the share token.",
	'# Placeholders look like "<NAME>"; regenerate with',
	"# `npm run sep1 -w scripts/harness` once the vault is deployed.",
]

const GENERATED_HEADER = [
	"# SEP-1 asset metadata (stellar.toml) for the share token.",
	'# Generated by `npm run sep1 -w scripts/harness`; placeholders look like "<NAME>".',
]

export function parseOperatorValues(json: unknown): OperatorValues {
	if (typeof json !== "object" || json === null || Array.isArray(json))
		throw new Error("operator values must be a JSON object")
	const result: OperatorValues = {}
	for (const [key, value] of Object.entries(json)) {
		if (!(OPERATOR_FIELDS as readonly string[]).includes(key))
			throw new Error(`unknown operator field "${key}"`)
		if (typeof value !== "string")
			throw new Error(`operator field "${key}" must be a string`)
		if (value === "")
			throw new Error(`operator field "${key}" must not be empty`)
		if (
			key === "anchor_asset_type" &&
			!(ANCHOR_ASSET_TYPES as readonly string[]).includes(value)
		)
			throw new Error(
				`operator field "anchor_asset_type" must be one of ${ANCHOR_ASSET_TYPES.join(", ")}`,
			)
		if (key === "ORG_URL" && !value.startsWith("https://"))
			throw new Error('operator field "ORG_URL" must start with "https://"')
		if (key === "code" && value.length > CODE_LIMIT)
			throw new Error(
				`operator field "code" must be at most ${CODE_LIMIT} characters`,
			)
		if (key === "name" && value.length > NAME_LIMIT)
			throw new Error(
				`operator field "name" must be at most ${NAME_LIMIT} characters`,
			)
		if (key === "status" && !(STATUSES as readonly string[]).includes(value))
			throw new Error(
				`operator field "status" must be one of ${STATUSES.join(", ")}`,
			)
		result[key as OperatorField] = value
	}
	return result
}

const LONE_SURROGATE =
	/[\ud800-\udbff](?![\udc00-\udfff])|(?<![\ud800-\udbff])[\udc00-\udfff]/

function quote(value: string, field: string): string {
	if (LONE_SURROGATE.test(value))
		throw new Error(`"${field}" has an unpaired surrogate`)
	return JSON.stringify(value).replace(/\x7f/g, "\\u007f")
}
const open = (field: string): string => quote(`<${field}>`, field)

function missingField(
	field: string,
	reason: string,
	missing: MissingField[],
): string {
	missing.push({ field, reason })
	return open(field)
}

function limited(
	value: string,
	limit: number,
	field: string,
	missing: MissingField[],
): string {
	if (value.length <= limit) return quote(value, field)
	missing.push({
		field,
		reason: `${value.length} characters, over SEP-1's ${limit}-character limit; set \`${field}\` in SEP1_OPERATOR`,
	})
	return open(field)
}

function operatorOrOpen(
	operator: OperatorValues,
	field: OpenField,
	missing: MissingField[],
): string {
	const value = operator[field]
	return value !== undefined
		? quote(value, field)
		: missingField(field, "set it in SEP1_OPERATOR", missing)
}

function documentationLines(
	operator: OperatorValues,
	missing: MissingField[],
): string[] {
	return DOCUMENTATION_FIELDS.map(
		(field) => `${field} = ${operatorOrOpen(operator, field, missing)}`,
	)
}

// The kit's own default, not SEP-1's rule: derived from the network (`live`
// on the public network, `test` elsewhere) unless the operator overrides it.
function status(
	inputs: Sep1Inputs,
	operator: OperatorValues,
	missing: MissingField[],
): string {
	if (operator.status !== undefined) return quote(operator.status, "status")
	if (inputs.networkPassphrase === undefined)
		return missingField("status", "no network passphrase given", missing)
	return quote(
		inputs.networkPassphrase === Networks.PUBLIC ? "live" : "test",
		"status",
	)
}

// `code` and `name` take the operator's value over the chain's, so a
// deployment whose on-chain value is unwanted, or too long, can be renamed
// without editing the generated file by hand.
function overridable(
	field: "code" | "name",
	limit: number,
	chainValue: string | undefined,
	operator: OperatorValues,
	missing: MissingField[],
): string {
	const value = operator[field] ?? chainValue
	if (value === undefined)
		return missingField(field, "no share token deployed yet", missing)
	return limited(value, limit, field, missing)
}

function currencyLines(
	inputs: Sep1Inputs,
	operator: OperatorValues,
	missing: MissingField[],
): string[] {
	const token = inputs.shareToken
	const noToken = (field: string): string =>
		missingField(field, "no share token deployed yet", missing)

	const code = overridable("code", CODE_LIMIT, token?.code, operator, missing)
	const contract = token
		? quote(token.contract, "contract")
		: noToken("contract")
	const displayDecimals = token
		? String(Math.min(token.decimals, DISPLAY_DECIMALS_LIMIT))
		: noToken("display_decimals")
	const name = overridable("name", NAME_LIMIT, token?.name, operator, missing)
	const report = inputs.report
	const attestationOfReserve =
		report && report.proofUri !== ""
			? quote(report.proofUri, "attestation_of_reserve")
			: missingField(
					"attestation_of_reserve",
					report
						? "the latest report's proof_uri is empty"
						: "no accepted attestation report yet",
					missing,
				)

	const lines = [
		`code = ${code}`,
		`contract = ${contract}`,
		`status = ${status(inputs, operator, missing)}`,
		`display_decimals = ${displayDecimals}`,
		`name = ${name}`,
		`desc = ${operatorOrOpen(operator, "desc", missing)}`,
		`image = ${operatorOrOpen(operator, "image", missing)}`,
		"is_asset_anchored = true",
		`anchor_asset_type = ${operatorOrOpen(operator, "anchor_asset_type", missing)}`,
		`anchor_asset = ${operatorOrOpen(operator, "anchor_asset", missing)}`,
	]
	if (report) {
		lines.push(`# proof hash: ${report.proofHash}`)
		lines.push(
			`# accepted at: ${new Date(Number(report.acceptedAt) * 1000).toISOString()}`,
		)
	}
	lines.push(`attestation_of_reserve = ${attestationOfReserve}`)
	lines.push(
		`redemption_instructions = ${operatorOrOpen(operator, "redemption_instructions", missing)}`,
	)
	return lines
}

function isEmptyInputs(inputs: Sep1Inputs): boolean {
	return Object.keys(inputs).length === 0
}

export function renderStellarToml(
	inputs: Sep1Inputs,
	operator: OperatorValues = {},
): { toml: string; missing: MissingField[] } {
	const missing: MissingField[] = []

	const networkPassphrase =
		inputs.networkPassphrase !== undefined
			? quote(inputs.networkPassphrase, "NETWORK_PASSPHRASE")
			: missingField(
					"NETWORK_PASSPHRASE",
					"no network passphrase given",
					missing,
				)

	const lines = [
		...(isEmptyInputs(inputs) ? TEMPLATE_HEADER : GENERATED_HEADER),
		"",
		`VERSION = ${quote(VERSION, "VERSION")}`,
		`NETWORK_PASSPHRASE = ${networkPassphrase}`,
		"",
		"[DOCUMENTATION]",
		...documentationLines(operator, missing),
		"",
	]
	if (inputs.feed !== undefined)
		lines.push(`# SEP-40 price feed: ${inputs.feed}`)
	lines.push("[[CURRENCIES]]", ...currencyLines(inputs, operator, missing))

	return { toml: `${lines.join("\n")}\n`, missing }
}
